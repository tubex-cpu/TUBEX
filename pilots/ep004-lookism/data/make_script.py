"""Builds data/script_full.py (LINES, CHAPTERS) from data/blocks.json (parsed from the script, 台本 v1). Text is used verbatim."""
import json, re
from pathlib import Path
D = Path(__file__).parent
B = json.loads((D / "blocks.json").read_text(encoding="utf-8"))
lines, chapters, last_ch = [], [], None
for bi, b in enumerate(B):
    newch = b["ch"] != last_ch
    if newch and last_ch is not None:
        m = re.match(r"(\d+b?)\.\s*(.*)", b["ch"])
        num, title = m.group(1), m.group(2)
        label = f"第{num.replace('b', '')}章" + ("②" if num.endswith("b") else "")
        chapters.append((f"{b['id']}_0", label, re.sub(r"[、。]", "", title).replace("：", " ")))
    last_ch = b["ch"]
    nxt_new = bi + 1 < len(B) and B[bi + 1]["ch"] != b["ch"]
    for k, t in enumerate(b["lines"]):
        ex = {}
        if k == 0:
            ex["scene"] = b["id"]
            ex["pre"] = 1.0 if newch else 0.4
        if k == len(b["lines"]) - 1:
            ex["gap"] = 1.2 if nxt_new else 0.8
        lines.append((f"{b['id']}_{k}", t, ex))
out = ["# Narration of ep004 ルッキズム (台本 v1). Generated by data/make_script.py — edit the script, not this file.", "LINES = ["]
out += [f" ({i!r}, {t!r}, {ex!r})," for i, t, ex in lines]
out += ["]", "CHAPTERS = ["] + [f" {c!r}," for c in chapters] + ["]"]
(D / "script_full.py").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(lines), "lines", len(chapters), "chapters"); [print(c) for c in chapters]
