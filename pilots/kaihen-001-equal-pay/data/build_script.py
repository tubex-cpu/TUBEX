"""Builds data/script_full.py (LINES, CHAPTERS, TAGS) from episodes/kaihen-001-equal-pay/05_script.md.
Scene = one '## Sxx' heading; each paragraph line under it = one narration line. Text is used verbatim.
Usage: python3 data/build_script.py"""
import re
from pathlib import Path
D = Path(__file__).parent
ROOT = D.parents[2]
md = (ROOT / "episodes/kaihen-001-equal-pay/05_script.md").read_text(encoding="utf-8")
body = md[md.index("# 第0章"):]
scenes, chapters, ch = [], [], None
for raw in body.split("\n"):
    l = raw.strip()
    if not l or l == "---" or l.startswith("- "):
        continue
    m = re.match(r"# (第[\d.]+章)\s*(.*?)（約\d+分）", l)
    if m:
        ch = (m.group(1), m.group(2)); continue
    m = re.match(r"## (S\d+[a-z]?)\s*(.*)", l)
    if m:
        sid = m.group(1).lower()
        tags = re.findall(r"【(.+?)】", m.group(2))
        title = re.sub(r"【.+?】", "", m.group(2)).strip()
        scenes.append({"id": sid, "title": title, "tags": tags, "ch": ch, "lines": []}); continue
    if l.startswith("#"):
        continue
    scenes[-1]["lines"].append(l)
lines, last = [], None
for si, s in enumerate(scenes):
    newch = s["ch"] != last
    if newch and last is not None:  # 第0章 has no card (the cold open)
        chapters.append((f"{s['id']}_0", s["ch"][0], s["ch"][1].replace("：", " ")))
    last = s["ch"]
    nxt_new = si + 1 < len(scenes) and scenes[si + 1]["ch"] != s["ch"]
    for k, t in enumerate(s["lines"]):
        ex = {}
        if k == 0:
            ex["scene"] = s["id"]; ex["pre"] = 1.0 if newch else 0.4
        if k == len(s["lines"]) - 1:
            ex["gap"] = 1.2 if nxt_new else 0.8
        lines.append((f"{s['id']}_{k}", t, ex))
tags = {s["id"]: s["tags"] for s in scenes}
out = ["# Narration of kaihen-001-equal-pay (台本 v0.2). Generated by data/build_script.py — edit the script, not this file.", "LINES = ["]
out += [f" ({i!r}, {t!r}, {ex!r})," for i, t, ex in lines]
out += ["]", "CHAPTERS = ["] + [f" {c!r}," for c in chapters] + ["]", f"TAGS = {tags!r}"]
(D / "script_full.py").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(scenes), "scenes", len(lines), "lines", len(chapters), "chapters", sum(len(t) for _, t, _ in lines), "chars")
